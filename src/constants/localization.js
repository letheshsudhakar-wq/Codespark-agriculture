const addTranslationPairs = (source, target, result) => {
  if (typeof source === 'string' && typeof target === 'string') {
    result.set(source, target);
    return;
  }
  if (!source || !target || typeof source !== 'object' || typeof target !== 'object') return;
  Object.keys(source).forEach((key) => addTranslationPairs(source[key], target[key], result));
};

const LOCALE_MAPS = Object.fromEntries(Object.keys(translations).map((language) => {
  const pairs = new Map();
  addTranslationPairs(translations.en, translations[language], pairs);
  return [language, pairs];
}));

export const localizeText = (value, language = 'en') => {
  if (typeof value !== 'string' || language === 'en') return value;
  return CONTENT_TRANSLATIONS[language]?.[value] || LOCALE_MAPS[language]?.get(value) || value;
};

export const localizeValue = (value, language = 'en') => {
  if (typeof value === 'string') return localizeText(value, language);
  if (Array.isArray(value)) return value.map((item) => localizeValue(item, language));
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(
    Object.entries(value).map(([key, child]) => [key, localizeValue(child, language)])
  );
};
